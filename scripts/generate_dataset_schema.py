#!/usr/bin/env python
"""Build reports/dataset_schema.md from the validated real-data report + adapter docs.

Feature meanings come from hep_quant.data.hls4ml_jets.FEATURE_DOCS (paper Table 1);
ranges/means/outlier counts come from reports/real_data_validation.json, so no
statistic is hand-typed.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from hep_quant.data.hls4ml_jets import FEATURE_DOCS  # noqa: E402

report = json.loads(Path("reports/real_data_validation.json").read_text())
stats = report["full_dataset"]["feature_stats"]

lines = [
    "# Dataset schema — OpenML `hls4ml_lhc_jets_hlf` (v1)",
    "",
    f"Statistics are over the full {report['full_dataset']['n_samples']:,}-jet file, taken from `reports/real_data_validation.json` "
    "(generated by `python -m hep_quant validate-data`). Meanings are limited to what the primary source states "
    "(Duarte et al., JINST 13 P07027, arXiv:1804.06913, Table 1 lists the observable families and parameters; a one-line "
    "definition of each is given there only by reference to Ref. [65], which was not reviewed). **Units are not stated in the sources "
    "reviewed** and are therefore left as 'not stated'.",
    "",
    "| Feature | Meaning (per source) | Unit | dtype | min | max | mean | std | #(abs z > 10) | Missing | Used | Reason |",
    "|---|---|---|---|---:|---:|---:|---:|---:|---:|---|---|",
]
for d in FEATURE_DOCS:
    s = stats[d.name]
    lines.append(
        f"| `{d.name}` | {d.meaning} | not stated | float32 | {s['min']:.4g} | {s['max']:.4g} | {s['mean']:.4g} | {s['std']:.4g} | "
        f"{s['n_abs_z_gt_10']} | 0 | yes | all 16 expert features kept, as in the hls4ml reference benchmark; no feature reduction |"
    )
lines += [
    "",
    "## Label",
    "",
    "`class` (nominal): `g` gluon, `q` light quark, `t` top quark, `w` W boson, `z` Z boson (label-encoded alphabetically 0–4). "
    "The five classes are ~20% each (see `reports/real_data_validation.md`).",
    "",
    "## Structure that is NOT used",
    "",
    "The Zenodo record (10.5281/zenodo.3602260) also distributes jet images and per-jet particle lists (up to 150 particles). "
    "The OpenML copy used here contains only the 16 high-level features, so the structured constituent information is not available "
    "to this benchmark. This is a scope limit of the chosen file, not a choice to discard information.",
]
Path("reports/dataset_schema.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote reports/dataset_schema.md")
